import type { Argv } from 'yargs';
import { noop } from '@spotify-confidence/shared-kernel';
import { createFactTableCmd, getFactTableCmd, listFactTablesCmd } from '@features/data/index.js';
import { safely } from '@utils/index.js';

export const factTablesCommand = {
  command: 'fact-tables',
  describe: 'List, inspect, and create fact tables',
  builder(yargs: Argv) {
    return yargs
      .command(
        'list',
        'List fact tables (one page unless --all is specified)',
        (y: Argv) =>
          y
            .option('page-size', { type: 'number', describe: 'Maximum resources per page' })
            .option('page-token', { type: 'string', describe: 'Continuation token' })
            .option('filter', { type: 'string', describe: 'Lucene query string filter' })
            .option('show-deleted', { type: 'boolean', describe: 'Include deleted fact tables' })
            .option('order-by', {
              type: 'string',
              describe: 'Sort fields, e.g. displayName:desc,createTime:asc',
            })
            .option('all', { type: 'boolean', describe: 'Traverse pages within explicit bounds' })
            .option('max-pages', { type: 'number', describe: 'Page bound for --all (1–1000)' })
            .option('max-items', {
              type: 'number',
              describe: 'Resource bound for --all (1–100000)',
            }),
        safely(listFactTablesCmd),
      )
      .command(
        'get [name]',
        'Get a fact table, including its current lifecycle state',
        (y: Argv) =>
          y
            .positional('name', { type: 'string', describe: 'Resource name: factTables/<id>' })
            .option('name', {
              type: 'string',
              demandOption: true,
              describe: 'Resource name: factTables/<id> (or supply it positionally)',
            }),
        safely(getFactTableCmd),
      )
      .command(
        'create',
        'Create one fact table from a resource JSON file',
        (y: Argv) =>
          y
            .option('from-file', {
              type: 'string',
              demandOption: true,
              describe: 'FactTable resource JSON file',
            })
            .option('id', {
              type: 'string',
              describe: 'Optional resource ID (otherwise generated by the service)',
            }),
        safely(createFactTableCmd),
      )
      .demandCommand(1, 'Available actions: list, get, create')
      .strict();
  },
  handler: noop,
};
